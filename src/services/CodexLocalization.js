export function getCodexCategoryName(cat, lang) {
  const catId = typeof cat === 'string' ? cat : cat?.id;
  const defaultName = typeof cat === 'object' ? cat?.name : cat;
  const dict = CATEGORY_NAMES[lang] || {};
  return dict[catId] || defaultName;
}

export function getCodexArticle(rawArt, lang) {
  const artId = typeof rawArt === 'string' ? rawArt : rawArt?.id;
  const langArticles = CODEX_ARTICLES[lang] || {};
  if (langArticles[artId]) {
    return {
      ...(typeof rawArt === 'object' ? rawArt : {}),
      ...langArticles[artId]
    };
  }
  return rawArt;
}
