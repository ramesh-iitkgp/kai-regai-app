export function getLocalizedCategoryName(catKey, lang) {
  const dict = CATEGORIES[lang] || {};
  return dict[catKey] || catKey.replace('_', ' ');
}

export function getLocalizedQuestionData(question, lang) {
  const qDict = QUESTIONS[lang] || {};
  const optDict = OPTIONS[lang] || {};

  const transQ = qDict[question.id] || {};
  const localizedOptions = (question.options || []).map(opt => {
    const transOpt = optDict[opt.id] || {};
    return {
      ...opt,
      label: transOpt.label || opt.label,
      desc: transOpt.desc || opt.desc
    };
  });

  return {
    ...question,
    title: transQ.title || question.title,
    subtitle: transQ.subtitle || question.subtitle,
    options: localizedOptions
  };
}
