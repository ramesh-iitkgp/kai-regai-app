class I18nService {
  constructor() {
    this.currentLanguage = this.loadLanguage();
  }

  loadLanguage() {
    if (typeof window !== 'undefined' && window.localStorage) {
      const saved = window.localStorage.getItem('kai_user_language');
      if (saved && TRANSLATIONS[saved]) {
        return saved;
      }
    }
    return 'en';
  }

  getLanguage() {
    return this.currentLanguage;
  }

  setLanguage(langCode) {
    if (TRANSLATIONS[langCode]) {
      this.currentLanguage = langCode;
      if (typeof window !== 'undefined' && window.localStorage) {
        window.localStorage.setItem('kai_user_language', langCode);
      }
    }
  }

  t(key, fallback = '') {
    const langDict = TRANSLATIONS[this.currentLanguage] || TRANSLATIONS['en'];
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    // Strict fallback to English dictionary if key is missing in active language
    const enDict = TRANSLATIONS['en'];
    if (enDict && enDict[key] !== undefined) {
      return enDict[key];
    }
    return fallback || key;
  }

  getMonthNames() {
    const langDict = TRANSLATIONS[this.currentLanguage] || TRANSLATIONS['en'];
    return langDict.months || TRANSLATIONS['en'].months;
  }

  getSupportedLanguages() {
    return SUPPORTED_LANGUAGES;
  }
}

export const i18n = new I18nService();
